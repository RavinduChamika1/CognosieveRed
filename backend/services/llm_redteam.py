async def run_llm_redteam(
    llm_endpoint_url: str,
    scan_id: str,
    business_impact_multiplier: float = 1.0,
    exposure_factor: float = 1.0,
    audit_callback=None,
    status_callback=None,
) -> List[Dict[str, Any]]:
    """
    Main entry point called by the scan orchestrator (STEP 0).

    1. Checks if promptfoo is available; if not, returns a single informational
       finding explaining it must be installed and skips silently.
    2. Writes a promptfoo YAML config to a temp directory.
    3. Runs ``promptfoo redteam run`` as a subprocess.
    4. Exports results to JSON.
    5. Parses results into the Finding schema.
    6. Returns raw findings (NOT yet Gemini-triaged — that happens in the orchestrator).

    All adversarial prompts stay within this temporary directory and the
    structured audit log; they are never forwarded to any other target.
    """
    def _audit(event: str, detail: str):
        if audit_callback:
            audit_callback(scan_id, event, detail)
        else:
            logger.info(f"[{scan_id}] {event}: {detail}")

    def _status(step: str, pct: int, msg: str):
        if status_callback:
            status_callback(scan_id, step, pct, msg)
        else:
            logger.info(f"[{scan_id}] {step} {pct}% — {msg}")

    _status("llm_redteam", 1, f"Starting LLM red-team against {llm_endpoint_url}")

    if not _is_promptfoo_available():
        _audit(
            "LLM_REDTEAM_SKIPPED",
            "promptfoo CLI not found on PATH. Install with: npm install -g promptfoo. "
            "LLM red-team stage skipped; web scan will proceed normally."
        )
        logger.warning(
            "promptfoo is not installed. "
            "LLM red-team stage skipped. "
            "Install with: npm install -g promptfoo"
        )
        # Return a single informational finding so the report shows the skip reason
        return [{
            "id": str(uuid.uuid4()),
            "_llm_finding_counter": 1,
            "title": "LLM Red-Team: promptfoo Not Installed (Stage Skipped)",
            "severity": "Low",
            "cvss_score": 1.0,
            "cvss_vector": "CVSS:3.1/AV:N/AC:H/PR:H/UI:R/S:U/C:N/I:N/A:N",
            "cwe_id": "OWASP-LLM-TOOL-MISSING",
            "owasp_category": "LLM Red-Team Stage (OWASP Top 10 for LLM Applications 2025)",
            "mitre_attack_technique": None,
            "affected_url": llm_endpoint_url,
            "description": (
                "The LLM red-team stage was requested but skipped because promptfoo is not installed "
                "in the backend environment. Install with: npm install -g promptfoo (requires Node.js). "
                "Re-run the scan after installation to get OWASP LLM Top 10 coverage."
            ),
            "evidence": {"request": "", "response": ""},
            "ai_verdict": "needs_review",
            "ai_reasoning": "Stage skipped — tool not installed.",
            "novel_pattern_flag": False,
            "remediation": "Install promptfoo: npm install -g promptfoo (requires Node.js >= 18).",
            "references": ["https://promptfoo.dev/docs/red-team/", "https://owasp.org/www-project-top-10-for-large-language-model-applications/"],
            "_llm_plugin_id": "n/a",
            "_llm_strategy": "n/a",
            "_llm_owasp_key": "LLM01",
            "_llm_promptfoo_reason": "Tool not installed",
            "source": "llm_redteam",
        }]

    with tempfile.TemporaryDirectory(prefix="cognosieve_llm_") as tmpdir:
        tmp_path = Path(tmpdir)
        config_file = tmp_path / "promptfooconfig.yaml"
        results_file = tmp_path / "results.json"

        # Write config
        config_dict = _build_promptfoo_config(llm_endpoint_url)
        import yaml  # type: ignore
        try:
            with open(config_file, "w", encoding="utf-8") as fh:
                yaml.safe_dump(config_dict, fh, default_flow_style=False, sort_keys=False)
        except ImportError:
            # PyYAML not installed – write JSON config (promptfoo accepts both)
            config_file = tmp_path / "promptfooconfig.json"
            with open(config_file, "w", encoding="utf-8") as fh:
                json.dump(config_dict, fh, indent=2)

        _status("llm_redteam", 3, "promptfoo config written, starting red-team run")
        _audit("LLM_REDTEAM_START", f"Invoking promptfoo against {llm_endpoint_url}")

        env = {**os.environ}

        # ----------------------------------------------------------------
        # 1. Run the red-team
        # ----------------------------------------------------------------
        try:
            proc = await asyncio.create_subprocess_exec(
                "promptfoo", "redteam", "run",
                "--config", str(config_file),
                "--output", str(results_file),
                "--no-cache",
                cwd=str(tmp_path),
                env=env,
                stdout=asyncio.subprocess.PIPE,
                stderr=asyncio.subprocess.PIPE,
            )
            stdout, stderr = await asyncio.wait_for(proc.communicate(), timeout=300)
            rc = proc.returncode

            stdout_text = stdout.decode("utf-8", errors="replace") if stdout else ""
            stderr_text = stderr.decode("utf-8", errors="replace") if stderr else ""

            if rc != 0:
                logger.warning(
                    f"promptfoo redteam run exited {rc}. "
                    f"stderr: {stderr_text[:500]}"
                )
                _audit(
                    "LLM_REDTEAM_WARN",
                    f"promptfoo exited with code {rc}. "
                    f"stdout={stdout_text[:200]} stderr={stderr_text[:200]}"
                )

        except asyncio.TimeoutError:
            logger.error("promptfoo timed out after 300 s")
            _audit("LLM_REDTEAM_TIMEOUT", "promptfoo timed out after 300 s; partial results may have been written.")
        except Exception as exc:
            logger.error(f"promptfoo subprocess failed: {exc}", exc_info=True)
            _audit("LLM_REDTEAM_ERROR", f"promptfoo subprocess failed: {exc}")
            return []

        _status("llm_redteam", 8, "promptfoo run completed, parsing results")

        # ----------------------------------------------------------------
        # 2. Parse results
        # ----------------------------------------------------------------
        if not results_file.exists():
            _audit(
                "LLM_REDTEAM_NO_RESULTS",
                "No results.json produced by promptfoo. "
                "The LLM endpoint may be unreachable or returned unexpected format."
            )
            logger.warning("promptfoo produced no results.json — skipping LLM findings.")
            return []

        try:
            with open(results_file, "r", encoding="utf-8") as fh:
                results_json = json.load(fh)
        except Exception as exc:
            logger.error(f"Failed to parse promptfoo results.json: {exc}")
            _audit("LLM_REDTEAM_PARSE_ERROR", f"results.json parse error: {exc}")
            return []

        raw_findings = _parse_promptfoo_results(
            results_json=results_json,
            llm_endpoint_url=llm_endpoint_url,
            business_impact_multiplier=business_impact_multiplier,
            exposure_factor=exposure_factor,
        )

        _audit(
            "LLM_REDTEAM_COMPLETE",
            f"promptfoo red-team completed. {len(raw_findings)} failed test(s) found against {llm_endpoint_url}. "
            f"Adversarial prompts contained within audit trail only."
        )
        _status("llm_redteam", 10, f"LLM red-team done: {len(raw_findings)} raw findings")

        return raw_findings
