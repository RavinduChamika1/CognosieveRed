"""
LLM Red-Teaming Service (OWASP Top 10 for LLM Applications 2025)
=================================================================
Invokes promptfoo as a CLI subprocess against a user-supplied LLM endpoint,
parses the results.json output into the same Finding schema used for ZAP alerts,
and returns raw findings ready for the existing Gemini triage + scoring pipeline.

This module is invoked as STEP 0 in the scan orchestrator ONLY when
``llm_endpoint_url`` is present in the scan parameters. If the field is blank
the module is never imported into the hot path and the pipeline is unchanged.

Authorization contract (non-negotiable, same rules as ZAP):
  - The caller MUST have already verified ``authorization_confirmation=True``.
  - Adversarial prompts generated by promptfoo are sent ONLY to llm_endpoint_url.
  - They are never logged in a way that exposes them outside this app's audit trail.
"""

